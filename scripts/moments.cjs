// Stages the big moments and screenshots each: parry flash, slam leap and crater, javelin pin, hook, charge.
const { chromium } = require('playwright');
const url = process.argv[2] || 'http://localhost:4173/';
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto(url);
  await page.waitForFunction(() => window.__room);
  const shot = (n) => page.screenshot({ path: `shots/m-${n}.png` });
  const park = () => page.evaluate(() => { for (const e of window.__room.enemies) if (e.kind !== 'butcher') Object.assign(e, { x: e.home.x, y: e.home.y, cooldown: 99 }); });
  await page.evaluate(() => Object.assign(window.__room.heroes[0], { x: 9, y: 7.4 }));
  await park();
  await page.waitForFunction(() => { const a = window.__room.enemies[0].attack; window.__room.heroes[0].hp = 100; return a && a.kind === 'cleave' && a.windup - a.t < 0.25 && a.t < a.windup; }, null, { timeout: 30000 }).catch(() => console.log('no cleave'));
  await shot('parry-window');
  await page.waitForFunction(() => { const r = window.__room, a = r.enemies[0].attack; r.heroes[0].hp = 100; Object.assign(r.heroes[0], { x: 9, y: 7.4 }); for (const e of r.enemies) if (e.kind !== 'butcher') e.cooldown = 99; return a && a.kind === 'slam' && a.t > a.windup * 0.75; }, null, { timeout: 60000 }).catch(() => console.log('no slam'));
  await shot('slam-leap');
  await page.waitForTimeout(500);
  await shot('slam-crater');
  await page.evaluate(() => { const r = window.__room; Object.assign(r.enemies[0], { x: 15, y: 13, cooldown: 99, attack: null, act: 'chase' }); const s = r.enemies.find((e) => e.kind === 'scrapper'); Object.assign(s, { x: 9, y: 4, act: 'chase', cooldown: 99 }); Object.assign(r.heroes[0], { x: 9, y: 9, hp: 100 }); });
  const box = await page.evaluate(() => [innerWidth / 2, innerHeight / 2]);
  await page.mouse.move(box[0], 30);
  await page.waitForTimeout(100);
  await page.keyboard.press('e');
  await page.waitForTimeout(700);
  await shot('javelin-pin');
  await page.evaluate(() => { const r = window.__room; const s = r.enemies.filter((e) => e.kind === 'scrapper')[1]; Object.assign(s, { x: 9, y: 4, act: 'chase', cooldown: 99 }); Object.assign(r.heroes[0], { x: 9, y: 11 }); });
  await page.keyboard.press('r');
  await page.waitForTimeout(100);
  await page.keyboard.press('e');
  await page.waitForTimeout(250);
  await shot('hook');
  await page.keyboard.press('q');
  await page.waitForTimeout(400);
  await page.mouse.down();
  await page.waitForTimeout(1100);
  await shot('charge');
  await page.mouse.up();
  await page.waitForTimeout(200);
  await shot('heavy');
  console.log(await page.evaluate(() => window.render_game_to_text()));
  console.log('errors', JSON.stringify(errors));
  await browser.close();
})();
