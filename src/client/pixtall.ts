/** The face, built once. */
export function tallFace(): PixFace {
  const glyphs: PixFace['glyphs'] = new Map();
  for (const [ch, spec] of Object.entries(ROWS)) {
    const rows = spec.split(' '), px: [number, number][] = [];
    rows.forEach((r, y) => [...r].forEach((c, x) => c === '#' && px.push([x, y])));
    glyphs.set(ch, { adv: rows[0].length + 1, px });
  }
  return { capH: 7, glyphs, avg: 5, depth: 6 };
}
